"""画面の改良案の評価関数（開発用。docs/ui.md の 2〜5 節）: 重み付きの合計（100 点満点）・順位・僅差の判定。

    python program/tools/ui_score.py

僅差の幅: 各基準の採点に ±1 段階（10 段階）のぶれがあるとすると、1 案の合計のぶれは σ1 = √Σ(w/10)²、
2 案の差のぶれは σd = σ1·√2。1 位と 2 位の差が 2σd 未満なら、採点のぶれで順位が入れ替わりうる（僅差）ので、
上位の案を組み合わせた複合案を混ぜて比べ直す。それでも僅差なら、次の行動 → 作り直しの確かさ → 合計 の順で決める。

採点は、案を画像にして（ui-variants.mjs）見比べてから付ける（CLAUDE.md）。2026-10 は、最初に文章だけで採点して選び、
あとから画像で採点し直した。両方を残す（IMAGE が正。TEXT は記録）。
"""

import math

CRITERIA = [  # (名前, 重み)
    ("次の行動がすぐ分かる", 20),
    ("状態と進み具合が見える", 15),
    ("読む量・判断の数が少ない", 15),
    ("どこに何があるかが一定", 15),
    ("見栄え・視覚の階層", 15),
    ("3D の見やすさ・操作の短さ", 10),
    ("作り直しの確かさ・保守性", 10),
]
WEIGHTS = [w for _, w in CRITERIA]
SIGMA1 = math.sqrt(sum((w / 10) ** 2 for w in WEIGHTS))
MARGIN = 2 * SIGMA1 * math.sqrt(2)

# 文章だけでの採点（記録。画像を見ずに付けたので、3D 全画面の案が模型を隠すことなどを見落としていた）
